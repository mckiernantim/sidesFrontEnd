#!/usr/bin/env node
/**
 * Writes src/environments/upload-allowlist.ts from UPLOAD_ALLOWLIST.
 *
 *   UPLOAD_ALLOWLIST=you@example.com,other@example.com npm run build
 *   UPLOAD_ALLOWLIST= npm run build          # open uploads to everyone
 *
 * The committed file stays email-free; this script runs before every build.
 */
const fs = require('fs');
const path = require('path');

const outPath = path.join(__dirname, '../src/environments/upload-allowlist.ts');
const raw = process.env.UPLOAD_ALLOWLIST || '';
const emails = raw
  .split(',')
  .map((s) => s.trim().toLowerCase())
  .filter(Boolean);

const contents = `/**
 * Upload allowlist — DO NOT put real emails in this committed file.
 *
 * Populated at build time from the UPLOAD_ALLOWLIST env var
 * (comma-separated). See scripts/inject-upload-allowlist.js.
 *
 * Semantics:
 *   - empty array  → any signed-in user may upload (open)
 *   - non-empty    → only listed emails may upload
 *
 * AUTO-GENERATED by scripts/inject-upload-allowlist.js — do not edit by hand.
 * Current build: ${emails.length ? `${emails.length} allowlisted email(s)` : 'OPEN (no allowlist)'}
 */
export const UPLOAD_ALLOWLIST: string[] = ${JSON.stringify(emails, null, 2)};

/** True when the user may start a script upload under the current allowlist. */
export function isUploadAllowed(
  email: string | null | undefined,
  allowlist: string[] = UPLOAD_ALLOWLIST
): boolean {
  if (!allowlist.length) {
    return true;
  }
  const normalized = email?.trim().toLowerCase();
  return !!normalized && allowlist.includes(normalized);
}
`;

fs.writeFileSync(outPath, contents, 'utf8');
console.log(
  emails.length
    ? `[upload-allowlist] restricted to ${emails.length} email(s)`
    : '[upload-allowlist] OPEN — any signed-in user may upload'
);
